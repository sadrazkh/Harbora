/// <summary>
/// <c>create_database</c> — a managed database (or cache, or broker) through
/// <see cref="IDatabaseProvisioningService"/>, the service <c>DatabasesController.Create</c> calls. The target
/// environment is resolved here, by project and environment name, and never left to the service's own
/// fallback: an environment id the workspace does not own quietly becomes the default environment there
/// (kept for the form's sake), so after a create the environment the database landed in is compared with
/// the one asked for, and a difference is a failure.
/// </summary>
public sealed class CreateDatabaseTool(
    HarboraDbContext db,
    IManagedServiceEngine engine,
    IDatabaseProvisioningService provisioning,
    ProjectAccessService access,
    AgentResourceResolver resolver,
    IOptions<BillingOptions> billing) : AgentWriteTool
{
    public override string Name => "create_database";

    public override string Description =>
        "Creates a managed database, cache or message broker in an environment: PostgreSQL, MySQL, MariaDB, Redis, " +
        "MongoDB, RabbitMQ, NATS or Meilisearch, with a version from get_catalog. The project and environment may be " +
        "ones an earlier step of the same plan creates. Provisioning is queued when the plan runs; credentials are " +
        "generated by Harbora and never returned. Does nothing by itself: it becomes a step of a plan the user approves.";

    public override string ParametersSchema =>
        """
        {
          "type": "object",
          "properties": {
            "name": { "type": "string", "description": "The database's name, for example 'shop-db'. Unique in the workspace." },
            "engine": { "type": "string", "description": "postgresql, mysql, mariadb, redis, mongodb, rabbitmq, nats or meilisearch — as get_catalog lists them." },
            "version": { "type": "string", "description": "One of the versions get_catalog lists for the engine. Omit for the newest offered." },
            "project": { "type": "string", "description": "The project's slug." },
            "environment": { "type": "string", "description": "The environment's slug. Omit for the project's default environment." },
            "size": { "type": "string", "description": "An instance size key from get_catalog. Omit for no size limit." },
            "redisEvictionPolicy": { "type": "string", "description": "Redis only: noeviction, allkeys-lru, allkeys-lfu, volatile-lru or volatile-ttl." },
            "redisMaxMemoryMb": { "type": "integer", "description": "Redis only: the memory cap in MB; 0 or omitted for none." }
          },
          "required": ["name", "engine", "project"],
          "additionalProperties": false
        }
        """;

    public override AgentToolKind Kind => AgentToolKind.SafeWrite;

    public override string? Capability => Capabilities.DatabasesManage;

    private static readonly ServiceRefusal NoPlacement = new(
        "You do not have permission to create a database in this environment.",
        "اجازهٔ ساختن دیتابیس در این محیط را ندارید.",
        nameof(DatabaseCreateRequest.EnvironmentId));

    private sealed record Input(
        string Name, ServiceCatalogEntry Entry, string Version, InstanceSize? Size,
        string? RedisPolicy, int? RedisMaxMemoryMb, string? Project, string? Environment);

    public override async Task<AgentValidation> ValidateAsync(
        JsonElement args, AgentToolContext context, AgentPlanScope scope, CancellationToken ct)
    {
        var (input, refusal) = await ReadAsync(args, ct);
        if (refusal is not null) return refusal;

        var (target, error, errorFa) = await TargetAsync(resolver, context, scope, input!.Project, input.Environment, ct);
        if (target is null) return AgentValidation.Refused(error!, errorFa!);

        var slug = DatabaseProvisioningService.Slugify(input.Name);
        if (scope.Planned.Any(p => p.Kind == AgentResourceKinds.Database && DatabaseProvisioningService.Slugify(p.Name) == slug))
            return AgentValidation.Refused(
                $"An earlier step of this plan already creates a database called '{input.Name}'.",
                $"یکی از مراحل قبلی همین برنامه دیتابیسی به نام «{input.Name}» می‌سازد.");

        var refusals = (await provisioning.ValidateCreateAsync(Request(context, input, target.Environment?.Id), ct)).ToList();
        if (target.Planned)
        {
            // The service judged placement against the workspace's default environment, the only one it could
            // find. Placement in an environment that does not exist yet is asked here instead: in a planned
            // project, of a placement no grant could name (the rule create_project itself applies); in a planned
            // environment of an existing project, of that project.
            refusals.RemoveAll(r => r.Field == nameof(DatabaseCreateRequest.EnvironmentId));
            var placement = target.Project is null
                ? new ResourcePlacement(null, null)
                : new ResourcePlacement(target.Project.Id, null);
            if (!await access.AllowsAsync(placement, Capabilities.DatabasesManage, ct)) refusals.Insert(0, NoPlacement);
        }
        if (refusals.Count > 0) return Refused(refusals);

        var (sizeEn, sizeFa) = DescribeSize(input.Size);
        var redisEn = input.Entry.Type == ManagedServiceType.Redis ? RedisEn(input) : "";
        var redisFa = input.Entry.Type == ManagedServiceType.Redis ? RedisFa(input) : "";
        var (plannedEn, plannedFa) = target.Planned ? PlannedNote(target) : ("", "");

        var warningsEn = new List<string>
        {
            "Provisioning is queued when the plan runs; the database is not ready until it finishes."
        };
        var warningsFa = new List<string>
        {
            "آماده‌سازی هنگام اجرای برنامه در صف قرار می‌گیرد؛ دیتابیس تا پایان آن آماده نیست."
        };
        if (await ChargesFirstHourAsync(context, ct))
        {
            warningsEn.Add("Its first hour is charged when it is created. The wallet can only be checked then, so it may still be refused for payment.");
            warningsFa.Add("هزینهٔ ساعت اول هنگام ساخت کسر می‌شود. کیف پول فقط در همان لحظه بررسی می‌شود، پس ممکن است ساخت به‌خاطر پرداخت رد شود.");
        }

        return new AgentValidation(true,
            TitleEn: $"Create database {input.Name}",
            TitleFa: $"ساخت دیتابیس {input.Name}",
            DetailEn: $"{input.Entry.DisplayName} {input.Version} in {target.Place}, {sizeEn}{redisEn}.{plannedEn}",
            DetailFa: $"{input.Entry.DisplayNameFa} نسخهٔ {input.Version} در {target.Place}، {sizeFa}{redisFa}.{plannedFa}",
            WarningsEn: warningsEn,
            WarningsFa: warningsFa,
            Creates: new AgentPlannedResource(AgentResourceKinds.Database, input.Name, target.ProjectSlug, target.EnvironmentSlug));
    }

    public override async Task<AgentToolResult> ExecuteAsync(JsonElement args, AgentToolContext context, CancellationToken ct)
    {
        var (input, refusal) = await ReadAsync(args, ct);
        if (refusal is not null) return FailedAs(refusal);

        var (target, error, errorFa) = await TargetAsync(resolver, context, scope: null, input!.Project, input.Environment, ct);
        if (target?.Environment is not { } environment) return AgentToolResult.Failed(error!, errorFa!);

        var outcome = await provisioning.CreateAsync(Request(context, input, environment.Id), ct);
        if (!outcome.Ok) return Failed(outcome.Refusals);
        var created = outcome.Value!;
        var links = new[] { DatabaseLink(created.ServiceId, created.Name) };

        if (created.EnvironmentId != environment.Id)
        {
            var landed = await db.Environments.AsNoTracking()
                .Where(e => e.Id == created.EnvironmentId)
                .Select(e => e.Project!.Slug + "/" + e.Slug)
                .FirstOrDefaultAsync(ct) ?? "?";
            return new AgentToolResult(false,
                AgentJson.Serialize(new { database = created.Name, requested = target.Place, landedIn = landed, created = true }),
                Error: $"Database {created.Name} was created, but in {landed} instead of {target.Place}. Nothing after this step ran; remove it or keep it deliberately.",
                ErrorFa: $"دیتابیس {created.Name} ساخته شد، ولی در {landed} به‌جای {target.Place}. مراحل بعدی اجرا نشدند؛ آن را حذف کنید یا آگاهانه نگه دارید.",
                Links: links);
        }

        return new AgentToolResult(true,
            AgentJson.Serialize(new
            {
                database = created.Name,
                engine = AgentResourceResolver.Lower(created.Type),
                version = created.Version,
                project = target.ProjectSlug,
                environment = target.EnvironmentSlug,
                size = input.Size?.Key,
                status = "provisioning queued"
            }),
            $"Created database {created.Name} ({input.Entry.DisplayName} {created.Version}) in {target.Place}; provisioning is queued.",
            $"دیتابیس {created.Name} ({input.Entry.DisplayNameFa} نسخهٔ {created.Version}) در {target.Place} ساخته شد؛ آماده‌سازی آن در صف است.",
            Links: links);
    }

    private static DatabaseCreateRequest Request(AgentToolContext context, Input input, Guid? environmentId) => new(
        context.WorkspaceId, context.UserId, input.Name, input.Entry.Type, input.Version, environmentId,
        input.Size?.Key, ServerId: null, input.RedisPolicy, input.RedisMaxMemoryMb, IpAddress: null);

    /// <summary>The arguments, checked against the catalogue the create form offers.</summary>
    private async Task<(Input? Input, AgentValidation? Refusal)> ReadAsync(JsonElement args, CancellationToken ct)
    {
        var name = AgentArgs.String(args, "name");
        if (name is null)
            return (null, AgentValidation.Refused("Say what the database is called (for example 'shop-db').",
                "بگویید نام دیتابیس چیست (مثلاً «shop-db»)."));

        var catalog = await ServiceCatalogReader.EffectiveAsync(db, engine, ct);
        var engineWords = AgentArgs.String(args, "engine");
        if (Engine(catalog, engineWords) is not { } entry)
            return (null, AgentValidation.Refused(
                $"Unknown engine '{engineWords}'. Offered: {Engines(catalog)}.",
                $"موتور «{engineWords}» شناخته نشد. موتورهای موجود: {Engines(catalog)}."));

        var versionWords = AgentArgs.String(args, "version");
        string version;
        if (versionWords is null) version = entry.Versions[0];
        else if (entry.Versions.FirstOrDefault(v => string.Equals(v, versionWords, StringComparison.OrdinalIgnoreCase)) is { } offered)
            version = offered;
        else
            return (null, AgentValidation.Refused(
                $"{entry.DisplayName} is not offered in version '{versionWords}'. Offered: {string.Join(", ", entry.Versions)}.",
                $"نسخهٔ «{versionWords}» برای {entry.DisplayNameFa} ارائه نمی‌شود. نسخه‌های موجود: {string.Join("، ", entry.Versions)}."));

        InstanceSize? size = null;
        if (AgentArgs.String(args, "size") is { } sizeWords)
        {
            size = await SizeAsync(db, sizeWords, ct);
            if (size is null)
            {
                var keys = await SizeKeysAsync(db, ct);
                return (null, AgentValidation.Refused(
                    $"There is no instance size '{sizeWords}'. Sizes: {keys}.",
                    $"اندازه‌ای به نام «{sizeWords}» وجود ندارد. اندازه‌های موجود: {keys}."));
            }
        }

        var redisPolicy = AgentArgs.String(args, "redisEvictionPolicy");
        var redisMaxMemoryMb = AgentArgs.Int(args, "redisMaxMemoryMb");
        if (entry.Type != ManagedServiceType.Redis && (redisPolicy is not null || redisMaxMemoryMb is > 0))
            return (null, AgentValidation.Refused(
                "redisEvictionPolicy and redisMaxMemoryMb apply only to Redis.",
                "redisEvictionPolicy و redisMaxMemoryMb فقط برای Redis معنا دارند."));

        return (new Input(name, entry, version, size, redisPolicy, redisMaxMemoryMb,
            AgentArgs.String(args, "project"), AgentArgs.String(args, "environment")), null);
    }

    private static string RedisEn(Input input) =>
        (input.RedisPolicy is null ? ", no eviction policy set" : $", eviction policy {input.RedisPolicy}") +
        (input.RedisMaxMemoryMb is > 0 ? $", memory cap {input.RedisMaxMemoryMb} MB" : "");

    private static string RedisFa(Input input) =>
        (input.RedisPolicy is null ? "، بدون سیاست حذف کلید" : $"، سیاست حذف کلید {input.RedisPolicy}") +
        (input.RedisMaxMemoryMb is > 0 ? $"، سقف حافظه {input.RedisMaxMemoryMb} مگابایت" : "");

    /// <summary>Whether creating it debits a first hour — billing on, and not the provider's own workspace,
    /// which <see cref="ResourceCreationBilling"/> exempts.</summary>
    private async Task<bool> ChargesFirstHourAsync(AgentToolContext context, CancellationToken ct) =>
        billing.Value.Enabled && !await db.Workspaces.IgnoreQueryFilters().AsNoTracking()
            .AnyAsync(w => w.Id == context.WorkspaceId && w.IsDefault, ct);
}
