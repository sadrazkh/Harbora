using FluentAssertions;
using Harbora.Domain.Common;
using Harbora.Infrastructure.Deployments;
using Xunit;

namespace Harbora.Tests;

/// <summary>
/// What every generated image looks like with no build args. These texts are not a description of
/// the templates but a copy of them from before any template could declare an <c>ARG</c>, and they were
/// run against that code first: an app with nothing to pass must keep the image it has always had, down
/// to the byte, because a changed Dockerfile is a rebuild of every layer on every deploy of every app.
/// </summary>
public class GeneratedDockerfileTests : IDisposable
{
    private readonly string _dir = Path.Combine(Path.GetTempPath(), "hbr-gen-" + Guid.NewGuid().ToString("N"));

    public GeneratedDockerfileTests() => Directory.CreateDirectory(_dir);

    public void Dispose()
    {
        try { Directory.Delete(_dir, recursive: true); } catch { /* best effort */ }
        GC.SuppressFinalize(this);
    }

    private void Place(string[] files)
    {
        foreach (var file in files)
        {
            var path = Path.Combine(_dir, file.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, file == "package.json" ? """{"scripts":{"start":"node a.js"}}""" : "");
        }
    }

    public static TheoryData<string[], int, ServiceKind, string> Templates() => new()
    {
        {
            ["package.json"], 3000, ServiceKind.Web,
            """
            # Auto-generated by Harbora (Node buildpack)
            FROM node:20-alpine
            WORKDIR /app
            COPY . .
            RUN npm install
            RUN npm run build --if-present
            ENV NODE_ENV=production
            ENV PORT=3000
            EXPOSE 3000
            CMD ["sh", "-c", "npm start"]
            """
        },
        {
            ["package.json", "pnpm-lock.yaml"], 3000, ServiceKind.Web,
            """
            # Auto-generated by Harbora (Node buildpack)
            FROM node:20-alpine
            WORKDIR /app
            COPY . .
            RUN corepack enable && pnpm install
            RUN pnpm run build || true
            ENV NODE_ENV=production
            ENV PORT=3000
            EXPOSE 3000
            CMD ["sh", "-c", "pnpm start"]
            """
        },
        {
            ["package.json", "yarn.lock"], 3000, ServiceKind.Web,
            """
            # Auto-generated by Harbora (Node buildpack)
            FROM node:20-alpine
            WORKDIR /app
            COPY . .
            RUN corepack enable && yarn install --frozen-lockfile || yarn install
            RUN yarn build || true
            ENV NODE_ENV=production
            ENV PORT=3000
            EXPOSE 3000
            CMD ["sh", "-c", "yarn start"]
            """
        },
        {
            ["Shop.csproj"], 8080, ServiceKind.Web,
            """
            # Auto-generated by Harbora (.NET buildpack)
            FROM mcr.microsoft.com/dotnet/sdk:9.0 AS build
            WORKDIR /src
            COPY . .
            RUN dotnet publish "Shop.csproj" -c Release -o /app

            FROM mcr.microsoft.com/dotnet/aspnet:9.0
            WORKDIR /app
            COPY --from=build /app ./
            ENV ASPNETCORE_URLS=http://+:8080
            EXPOSE 8080
            ENTRYPOINT ["dotnet", "Shop.dll"]
            """
        },
        {
            ["go.mod"], 8080, ServiceKind.Web,
            """
            # Auto-generated by Harbora (Go buildpack)
            FROM golang:1.22-alpine AS build
            WORKDIR /src
            COPY go.* ./
            RUN go mod download || true
            COPY . .
            RUN CGO_ENABLED=0 go build -o /app/server .

            FROM alpine:3.20
            RUN apk add --no-cache ca-certificates
            COPY --from=build /app/server /server
            ENV PORT=8080
            EXPOSE 8080
            CMD ["/server"]
            """
        },
        {
            ["composer.json"], 8081, ServiceKind.Web,
            """
            # Auto-generated by Harbora (PHP buildpack)
            FROM php:8.3-apache
            RUN a2enmod rewrite
            # Serve on the app's port instead of 80.
            RUN sed -ri "s/Listen 80/Listen 8081/" /etc/apache2/ports.conf \
             && sed -ri "s/:80>/:8081>/" /etc/apache2/sites-enabled/000-default.conf
            WORKDIR /var/www/html
            COPY . /var/www/html/
            RUN if [ -f composer.json ]; then curl -sS https://getcomposer.org/installer | php -- --install-dir=/usr/local/bin --filename=composer && composer install --no-dev --no-interaction || true; fi
            EXPOSE 8081
            """
        },
        {
            ["index.php"], 80, ServiceKind.Web,
            """
            # Auto-generated by Harbora (PHP buildpack)
            FROM php:8.3-apache
            RUN a2enmod rewrite
            # Serve on the app's port instead of 80.
            RUN sed -ri "s/Listen 80/Listen 80/" /etc/apache2/ports.conf \
             && sed -ri "s/:80>/:80>/" /etc/apache2/sites-enabled/000-default.conf
            WORKDIR /var/www/html
            COPY . /var/www/html/

            EXPOSE 80
            """
        },
        {
            ["requirements.txt", "app.py"], 5000, ServiceKind.Web,
            """
            # Auto-generated by Harbora (Python buildpack)
            FROM python:3.12-slim
            WORKDIR /app
            COPY . .
            RUN pip install --no-cache-dir -r requirements.txt
            ENV PYTHONUNBUFFERED=1
            ENV PORT=5000
            EXPOSE 5000
            CMD ["python", "app.py"]
            """
        },
        {
            ["pyproject.toml", "bot.py"], 5000, ServiceKind.Worker,
            """
            # Auto-generated by Harbora (Python buildpack)
            FROM python:3.12-slim
            WORKDIR /app
            COPY . .
            RUN pip install --no-cache-dir . || true
            ENV PYTHONUNBUFFERED=1
            CMD ["python", "bot.py"]
            """
        },
        {
            ["index.html"], 80, ServiceKind.Web,
            """
            # Auto-generated by Harbora (static buildpack)
            FROM nginx:alpine
            COPY . /usr/share/nginx/html
            EXPOSE 80
            """
        }
    };

    [Theory]
    [MemberData(nameof(Templates))]
    public void With_no_build_args_each_template_is_byte_for_byte_what_it_always_was(
        string[] files, int port, ServiceKind kind, string expected)
    {
        Place(files);

        Buildpacks.Detect(_dir, port, kind)!.Value.Dockerfile.ReplaceLineEndings("\n")
            .Should().Be(expected.ReplaceLineEndings("\n"));
    }
}
