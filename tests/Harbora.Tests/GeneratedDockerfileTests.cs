    public void Anything_else_does_not(string name) =>
        Harbora.Shared.Inspection.PublicBuildVariables.IsPublic(name).Should().BeFalse();

    // --- Through the pipeline --------------------------------------------------------------------

    private static Fakes.PipelineHarness GitApp(params (string File, string Content)[] files)
    {
        var h = new Fakes.PipelineHarness(sourceType: AppSourceType.GitRepository).WithGitSource();
        foreach (var (file, content) in files) File.WriteAllText(Path.Combine(h.WorkDir, file), content);
        return h;
    }

    private static void AddVariable(
        Fakes.PipelineHarness h, string key, string value, bool availableAtBuild = false, bool secret = false)
    {
        h.Db.EnvironmentVariables.Add(new Harbora.Domain.Apps.EnvironmentVariable
        {
            AppId = h.App.Id, Key = key, IsSecret = secret, AvailableAtBuild = availableAtBuild,
            Value = secret ? h.Protector.Protect(value) : value
        });
        h.Db.SaveChanges();
    }

    private static async Task<(IReadOnlyDictionary<string, string> Args, string Dockerfile)> DeployAsync(Fakes.PipelineHarness h)
    {
        await h.RunAsync(h.QueueDeployment());

        var build = h.Docker.BuildRequests.Should().ContainSingle().Subject;
        return (build.BuildArgs, File.ReadAllText(Path.Combine(h.WorkDir, build.Dockerfile)).ReplaceLineEndings("\n"));
    }

    private const string RealNodeApp = """{"scripts":{"start":"node a.js"}}""";

    [Fact]
    public async Task On_node_a_marked_variable_and_an_unmarked_public_one_reach_the_build_and_nothing_else_does()
    {
        using var h = GitApp(("package.json", RealNodeApp));
        AddVariable(h, "BUILD_FLAG", "yes", availableAtBuild: true);
        AddVariable(h, "NPM_TOKEN", "hunter2", availableAtBuild: true, secret: true);
        AddVariable(h, "NEXT_PUBLIC_API", "https://api.shop.example");
        AddVariable(h, "DATABASE_PASSWORD", "not-this-one");

        var (args, dockerfile) = await DeployAsync(h);

        args.Keys.Should().BeEquivalentTo("BUILD_FLAG", "NPM_TOKEN", "NEXT_PUBLIC_API");
        args["NPM_TOKEN"].Should().Be("hunter2", "a marked secret reaches the build decrypted, as it always did");
        dockerfile.Should().Contain("ARG BUILD_FLAG\nARG NEXT_PUBLIC_API\nARG NPM_TOKEN\nRUN npm install\n");
        dockerfile.Should().NotContain("hunter2").And.NotContain("https://api.shop.example").And.NotContain("DATABASE_PASSWORD");
    }

    [Fact]
    public async Task On_node_a_public_variable_from_a_config_group_reaches_the_build()
    {
        using var h = GitApp(("package.json", RealNodeApp));
        var group = new Harbora.Domain.Apps.ConfigGroup { WorkspaceId = h.Workspace.Id, Name = "shared" };
        h.Db.ConfigGroups.Add(group);
        h.Db.ConfigGroupEntries.Add(new Harbora.Domain.Apps.ConfigGroupEntry
        {
            ConfigGroupId = group.Id, Key = "NEXT_PUBLIC_FROM_GROUP", Value = "yes"
        });
        h.Db.AppConfigGroups.Add(new Harbora.Domain.Apps.AppConfigGroup { AppId = h.App.Id, ConfigGroupId = group.Id, AttachOrder = 1 });
        h.Db.SaveChanges();

        var (args, dockerfile) = await DeployAsync(h);

        args.Should().Contain("NEXT_PUBLIC_FROM_GROUP", "yes");
        dockerfile.Should().Contain("ARG NEXT_PUBLIC_FROM_GROUP\n");
    }

    [Fact]
    public async Task On_python_only_the_mark_decides()
    {
        using var h = GitApp(("requirements.txt", "flask"), ("app.py", ""));
        AddVariable(h, "BUILD_FLAG", "yes", availableAtBuild: true);
        AddVariable(h, "VITE_MARKED", "yes", availableAtBuild: true);
        AddVariable(h, "VITE_NOT_MARKED", "no");

        var (args, dockerfile) = await DeployAsync(h);

        args.Keys.Should().BeEquivalentTo("BUILD_FLAG", "VITE_MARKED");
        dockerfile.Should().Contain("ARG BUILD_FLAG\nARG VITE_MARKED\nRUN pip install").And.NotContain("VITE_NOT_MARKED");
    }

    [Theory]
    [InlineData("Shop.csproj", "<Project />", "RUN dotnet publish")]
    [InlineData("go.mod", "module x", "COPY go.* ./")]
    [InlineData("composer.json", "{}", "RUN curl -fsS https://getcomposer.org/installer")]
    public async Task On_each_other_image_a_marked_variable_is_declared_and_passed(string marker, string content, string next)
    {
        using var h = GitApp((marker, content));
