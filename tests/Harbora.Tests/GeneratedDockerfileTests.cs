    [Fact]
    public void A_composer_failure_stops_the_deployment_rather_than_shipping_an_image_with_no_vendor_folder()
    {
        Place(["composer.json"]);

        var dockerfile = Buildpacks.Detect(_dir, 80)!.Value.Dockerfile;

        dockerfile.Should().NotContain("|| true", "the release task would then fail after the database was billed");
        dockerfile.Should().NotContain("| php", "a pipe hides a failed download");
        dockerfile.Should().Contain("composer install --no-dev --no-interaction");
        dockerfile.Should().Contain("git unzip", "what composer needs to unpack anything");
        dockerfile.IndexOf("git unzip", StringComparison.Ordinal).Should()
            .BeLessThan(dockerfile.IndexOf("composer install", StringComparison.Ordinal));
    }

    [Fact]
    public void Composer_is_told_it_may_run_as_root_or_it_turns_off_the_script_laravel_needs()
