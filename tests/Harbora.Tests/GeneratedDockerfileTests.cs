    [Fact]
    public void Laravel_is_served_from_public_with_rewrites_on_and_may_write_where_it_writes()
    {
        Place(["composer.json", "artisan"]);

        var dockerfile = Buildpacks.Detect(_dir, 80)!.Value.Dockerfile;

        dockerfile.Should().Contain("DocumentRoot /var/www/html/public");
        dockerfile.Should().Contain("a2enmod rewrite");

        // After the install, which writes into bootstrap/cache as root.
        dockerfile.IndexOf("chown -R www-data:www-data bootstrap/cache storage", StringComparison.Ordinal).Should()
            .BeGreaterThan(dockerfile.IndexOf("composer install", StringComparison.Ordinal));

        // Before it, which fails on a tree that left bootstrap/cache out.
        dockerfile.IndexOf("mkdir -p bootstrap/cache", StringComparison.Ordinal).Should()
            .BeLessThan(dockerfile.IndexOf("composer install", StringComparison.Ordinal));
    }

