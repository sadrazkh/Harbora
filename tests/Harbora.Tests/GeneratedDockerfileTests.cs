    [Theory]
    [MemberData(nameof(ImagesWithABuildStep))]
    public void A_marked_variable_is_declared_before_the_build_step_and_nothing_else_about_the_image_changes(
        string[] files, ServiceKind kind, string firstStepThatCouldReadIt)
    {
        Place(files);
        var without = Buildpacks.Detect(_dir, 8080, kind)!.Value.Dockerfile.ReplaceLineEndings("\n");

        var pack = Buildpacks.Detect(_dir, 8080, kind, null, null, ["ZED", "BUILD_FLAG"])!.Value;
        var with = pack.Dockerfile.ReplaceLineEndings("\n");

        pack.BuildArgNames.Should().Equal("BUILD_FLAG", "ZED");
        with.Split('\n').Where(l => l.StartsWith("ARG ", StringComparison.Ordinal)).Should().Equal("ARG BUILD_FLAG", "ARG ZED");
        with.IndexOf("ARG ZED", StringComparison.Ordinal).Should()
            .BeLessThan(with.IndexOf(firstStepThatCouldReadIt, StringComparison.Ordinal));
        with.Replace("ARG BUILD_FLAG\nARG ZED\n", "").Should().Be(without);
    }

